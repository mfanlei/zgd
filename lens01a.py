#!/usr/bin/env python3
"""
ZGD 引力透镜验证 A（纯牛顿项 + 有效质光比 0.51）
=====================================================
使用纯牛顿偏折角公式与 SPARC 校准的有效质光比 0.51，
计算 15 个透镜系统的理论偏折角并与观测对比。
验证逻辑：若有效质光比 0.51 已扣除几何修正项的等效贡献，
          则纯牛顿项应与观测偏折角一致。
"""

import numpy as np

# ==================== 物理常数 ====================
G  = 6.67430e-11
C  = 2.99792458e8
MSUN = 1.98847e30
KPC = 3.085677581e19       # m / kpc

UPS_EFF  = 0.51            # SPARC 强核球组校准的有效质光比
UPS_OLD  = 0.7              # 原 SPARC 基准质光比

# ==================== 判定阈值 ====================
RATIO_LO = 0.80             # 中位比值下限（低于此值：低估）
RATIO_HI = 1.20             # 中位比值上限（高于此值：高估）

# ==================== 透镜数据 ====================
lens_data = [
    ("SDSS J0946+1006 (内环)", 2.5e11, 4.8, 1.43),
    ("SDSS J0946+1006 (外环)", 2.5e11, 4.8, 2.07),
    ("QSO 2237+0305",          3.0e11, 0.70, 0.90),
    ("Abell 1689",             2.0e14, 150.0, 45.0),
    ("B1608+656",              1.0e11, 3.0, 1.14),
    ("MG1549+3047",            2.0e10, 2.0, 0.85),
    ("B0218+357",              5.0e9,  1.0, 0.17),
    ("MG2016+112",             3.0e11, 5.0, 1.76),
    ("RXJ0911+0551",           1.5e11, 3.5, 1.24),
    ("Q0142-100",              8.0e10, 2.5, 1.12),
    ("B1600+434",              6.0e10, 2.0, 0.70),
    ("PKS1830-211",            4.0e10, 1.8, 0.50),
    ("B0712+472",              5.0e10, 2.0, 0.73),
    ("SDSS J0037-0942",        1.8e11, 3.5, 1.18),
    ("SDSS J0956+5100",        2.2e11, 4.0, 1.38),
]

print("ZGD 引力透镜验证 A（纯牛顿 + 有效质光比 0.51）")
print(f"{'系统':<25} {'b(kpc)':<8} {'α_pred':<10} {'θ_obs':<10} {'比值':<8}")
print("-" * 65)

ratios = []
for name, M_old, b_kpc, theta_obs in lens_data:
    M_true = M_old * (UPS_EFF / UPS_OLD)
    b_m = b_kpc * KPC
    M_kg = M_true * MSUN

    alpha_rad = 4 * G * M_kg / (C**2 * b_m)
    alpha_arcsec = alpha_rad * 206265
    ratio = alpha_arcsec / theta_obs
    ratios.append(ratio)
    print(f"{name:<25} {b_kpc:<8.1f} {alpha_arcsec:<10.4f} {theta_obs:<10.2f} {ratio:<8.3f}")

med = np.median(ratios)
avg = np.mean(ratios)

print("-" * 65)
print(f"有效透镜系统数: {len(ratios)}")
print(f"中位比值: {med:.3f}")
print(f"平均比值: {avg:.3f}")

# ==================== 判定 ====================
if RATIO_LO <= med <= RATIO_HI:
    print(f"判定: 中位比值 {med:.3f} 落在 [{RATIO_LO}, {RATIO_HI}] 内。")
    print("       有效质光比 0.51 下，纯牛顿项与观测偏折角基本一致。")
    print("       有效质光比 0.51 已扣除几何修正项的等效叠加。")
elif med < RATIO_LO:
    print(f"判定: 中位比值 {med:.3f} 低于 {RATIO_LO}。")
    print("       纯牛顿项系统性低估观测偏折角——有效质光比可能偏低，")
    print("       或几何修正项在透镜中仍有未被扣除的额外贡献。")
else:  # med > RATIO_HI
    print(f"判定: 中位比值 {med:.3f} 高于 {RATIO_HI}。")
    print("       纯牛顿项系统性高估观测偏折角——有效质光比可能偏高，")
    print("       或存在未被建模的系统误差。")